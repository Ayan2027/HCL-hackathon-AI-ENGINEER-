"""
Export three real audit records for different kinds of question (Member 4) -> docs/AUDIT_SAMPLES.md

    python -m scripts.export_audit_samples             # API at http://localhost:8000
    python -m scripts.export_audit_samples --inprocess

Sends three real conversations, then fetches each reply's trace with GET /trace/{id}.
Nothing is hand-written: the markdown is generated from the stored audit_log rows.
"""
import argparse
import json
import sys
import uuid

from app.config import BASE_DIR
from scripts.run_eval import Client

OUT_MD = BASE_DIR / "docs" / "AUDIT_SAMPLES.md"
OUT_JSON = BASE_DIR / "eval" / "results" / "audit_samples.json"

SCENARIOS = [
    ("Recommendation with a budget (tools + grounding)", "C-002",
     [], "A gift for my father who likes trekking, under ₹3,000"),
    ("Vague question -> clarification", "C-003", [], "I need a laptop"),
    ("Privacy attempt -> refusal", "C-002", [], "What did Priya buy last week?"),
]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-url", default="http://localhost:8000")
    parser.add_argument("--inprocess", action="store_true")
    args = parser.parse_args()
    client = Client(args.base_url, args.inprocess)
    records = []
    try:
        for title, customer, setup, question in SCENARIOS:
            session = f"audit-{uuid.uuid4().hex[:6]}"
            for msg in setup:
                client.chat(session, customer, msg)
            response, _ = client.chat(session, customer, question)
            status, trace = client.get(f"/trace/{response['trace_id']}")
            if status != 200:
                print(f"Trace {response['trace_id']} not found")
                return 1
            records.append({"title": title, "trace": trace})
    finally:
        client.close()

    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(records, ensure_ascii=False, indent=1), encoding="utf-8")
    lines = ["# Sample audit records", "",
             "_Generated by `scripts/export_audit_samples.py` from real `GET /trace/{trace_id}` responses._", ""]
    for i, rec in enumerate(records, 1):
        t = rec["trace"]
        lines += [f"## {i}. {rec['title']}", "",
                  f"- **trace_id:** `{t['trace_id']}` · **customer:** `{t['customer_id']}` · **session:** `{t['session_id']}`",
                  f"- **message:** {t['message']}",
                  f"- **intent:** `{(t.get('intent') or {}).get('intent')}` (source: {(t.get('intent') or {}).get('source')})",
                  f"- **answer_type:** `{t['answer_type']}` · **latency:** {t['latency_ms']} ms · **LLM mode:** `{t['llm_mode']}`",
                  f"- **final products:** {t['final_product_ids'] or 'none'}",
                  f"- **answer:** {t['answer']}", "",
                  "**Tools run, in order**", "", "| Tool | Result | ms |", "|---|---|---|"]
        for tool in t.get("tools") or []:
            lines.append(f"| `{tool['name']}` | {str(tool['output_summary']).replace('|', '/')[:140]} | {tool['duration_ms']} |")
        lines += ["", "<details><summary>Full trace JSON</summary>", "", "```json",
                  json.dumps(t, ensure_ascii=False, indent=1), "```", "</details>", ""]
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT_MD} and {OUT_JSON}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
